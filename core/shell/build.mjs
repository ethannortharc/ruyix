// Bundles src/ into client.js for the dsh browser module loader; React stays external (the host shares its copy).
// the factory's `require` hands out the host's single React (dsh ships 18.3) and its shared
// ui-primitives (MarkdownText).
import { build } from 'esbuild'
import { execFileSync } from 'node:child_process'

// The build's commit (with -dirty for uncommitted changes here), shown next to our version in the sidebar's foot.
const git = args => execFileSync('git', args, { encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).trim()
const commit = (() => { try { return git(['rev-parse', '--short', 'HEAD']) + (git(['status', '--porcelain', '.']) ? '-dirty' : '') } catch { return '' } })()
import { writeFileSync } from 'node:fs'

const { outputFiles } = await build({
  entryPoints: ['src/main.jsx'],
  bundle: true,
  write: false,
  format: 'cjs',
  platform: 'browser',
  target: 'es2022',
  jsx: 'automatic',
  minify: !process.argv.includes('--dev'),
  legalComments: 'none',
  loader: { '.css': 'text' },
  external: ['react', 'react-dom', 'react-dom/client', 'react/jsx-runtime', '@deepseek-ai/dsh-client-ui-primitives'],
  define: { 'process.env.NODE_ENV': '"production"', __RUYIX_COMMIT__: JSON.stringify(commit), __RUYIX_BUILT__: JSON.stringify(new Date().toISOString()) },
  logLevel: 'warning',
})

const body = outputFiles[0].text
// (the build's stamp for the server too: /api/ruyix/version says which build this is — the maps, ruyix status)
writeFileSync('build.json', `${JSON.stringify({ commit, built: new Date().toISOString() })}\n`)
writeFileSync('client.js', `// Generated by build.mjs from src/ — edit the sources, then run \`node build.mjs\`.
window.__ModuleLoader__.load({
  id: '@ruyix/shell',
  factory(require) {
    var module = { exports: {} }, exports = module.exports;
${body}
    return module.exports;
  },
});
`)
console.log(`client.js ${(body.length / 1024).toFixed(0)} KB`)
