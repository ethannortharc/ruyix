// Bundles src/ into client.js for dsh's browser module loader. React stays external (the page's own copy); the kit
// (@ruyix/world/kit) is bundled in. `--kit <path>`: take the kit from there instead (building inside Ruyix's repo).
import { build } from 'esbuild'
import { writeFileSync } from 'node:fs'
import { resolve } from 'node:path'

const at = process.argv.indexOf('--kit'), kit = at > 0 ? resolve(process.argv[at + 1]) : null
const { outputFiles } = await build({
  entryPoints: ['src/main.jsx'], bundle: true, write: false, format: 'cjs', platform: 'browser', target: 'es2022',
  jsx: 'automatic', minify: true, legalComments: 'none', loader: { '.css': 'text' }, logLevel: 'warning',
  external: ['react', 'react-dom', 'react-dom/client', 'react/jsx-runtime'],
  define: { 'process.env.NODE_ENV': '"production"' },
  ...(kit && { alias: { '@ruyix/world/kit': kit } }),
})
const id = JSON.parse((await import('node:fs')).readFileSync('package.json', 'utf8')).name
writeFileSync('client.js', `// Generated by build.mjs from src/ — edit the sources, then run \`node build.mjs\`.
window.__ModuleLoader__.load({
  id: ${JSON.stringify(id)},
  factory(require) {
    var module = { exports: {} }, exports = module.exports;
${outputFiles[0].text}
    return module.exports;
  },
});
`)
console.log(`client.js ${(outputFiles[0].text.length / 1024).toFixed(0)} KB`)
