// Bundles src/ into client.js for the dsh browser module loader. React stays external:
// the factory's `require` hands out the host's single React (dsh ships 18.3).
import { build } from 'esbuild'
import { writeFileSync } from 'node:fs'

const { outputFiles } = await build({
  entryPoints: ['src/main.jsx'],
  bundle: true,
  write: false,
  format: 'cjs',
  platform: 'browser',
  target: 'es2022',
  jsx: 'automatic',
  minify: !process.argv.includes('--dev'),
  legalComments: 'none',
  loader: { '.css': 'text' },
  external: ['react', 'react-dom', 'react-dom/client', 'react/jsx-runtime', '@deepseek-ai/dsh-client-ui-primitives'],
  define: { 'process.env.NODE_ENV': '"production"' },
  logLevel: 'warning',
})

// motion probes an optional package inside try/catch; resolve it to nothing up front.
const body = outputFiles[0].text.replaceAll('require("@emotion/is-prop-valid")', '({})')
writeFileSync('client.js', `// Generated by build.mjs from src/ — edit the sources, then run \`node build.mjs\`.
window.__ModuleLoader__.load({
  id: '@ruyix/agent-hub',
  factory(require) {
    var module = { exports: {} }, exports = module.exports;
${body}
    return module.exports;
  },
});
`)
console.log(`client.js ${(body.length / 1024).toFixed(0)} KB`)
