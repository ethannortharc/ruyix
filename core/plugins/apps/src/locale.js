/** A word outside dsh's locale (the desktop draws the app windows): {name} filled from params, en when zh lacks it. */
export const word = (lang, key, params = {}) => String((lang === 'zh' ? zh : en)[key] ?? en[key] ?? key).replace(/\{(\w+)\}/g, (m, k) => (params[k] ?? m))
