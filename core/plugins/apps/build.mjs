// Bundles src/ into client.js for the dsh browser module loader. React stays external: the factory's `require` hands
// out the host's shared copy. noVNC is bundled (MPL-2.0, its files unchanged but for the line below).
import { build } from 'esbuild'
import { readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { dirname, join } from 'node:path'

const require = createRequire(import.meta.url)

// noVNC's util/browser.js finds out at load time, with a top-level await, whether the browser decodes H.264 — a
// module format (CommonJS, what dsh's loader takes) cannot wait at the top. The same check, not waited for: the
// answer lands a moment later (TigerVNC sends no H.264 anyway). A noVNC whose line changed fails the build here.
const TLA = 'supportsWebCodecsH264Decode = await _checkWebCodecsH264DecodeSupport();'
const novncNoTopLevelAwait = {
  name: 'novnc-no-top-level-await',
  setup(b) {
    b.onLoad({ filter: /@novnc[\\/]novnc[\\/]core[\\/]util[\\/]browser\.js$/ }, args => {
      const src = readFileSync(args.path, 'utf8')
      if (!src.includes(TLA)) throw new Error(`noVNC changed: ${args.path} no longer has the line build.mjs rewrites`)
      return { contents: src.replace(TLA, '_checkWebCodecsH264DecodeSupport().then(v => { supportsWebCodecsH264Decode = v; }, () => {});'), loader: 'js' }
    })
  },
}

// noVNC's package exports only its RFB (core/rfb.js); the keyboard and key table vnc.jsx uses are files beside it
const novncFiles = {
  name: 'novnc-files',
  setup(b) {
    b.onResolve({ filter: /^@novnc\/novnc\/core\// }, args => ({ path: join(dirname(dirname(require.resolve('@novnc/novnc'))), args.path.slice('@novnc/novnc/'.length)) }))
  },
}

const { outputFiles } = await build({
  entryPoints: ['src/main.jsx'],
  bundle: true,
  write: false,
  format: 'cjs',
  platform: 'browser',
  target: 'es2022',
  jsx: 'automatic',
  minify: !process.argv.includes('--dev'),
  legalComments: 'none',
  loader: { '.css': 'text' },
  plugins: [novncNoTopLevelAwait, novncFiles],
  external: ['react', 'react-dom', 'react-dom/client', 'react/jsx-runtime', '@deepseek-ai/dsh-client-ui-primitives'],
  define: { 'process.env.NODE_ENV': '"production"' },
  logLevel: 'warning',
})

writeFileSync('client.js', `// Generated by build.mjs from src/ — edit the sources, then run \`node build.mjs\`.
// Bundles noVNC (https://github.com/novnc/noVNC), MPL-2.0.
window.__ModuleLoader__.load({
  id: '@ruyix/apps',
  factory(require) {
    var module = { exports: {} }, exports = module.exports;
${outputFiles[0].text}
    return module.exports;
  },
});
`)
console.log(`client.js ${(outputFiles[0].text.length / 1024).toFixed(0)} KB`)
